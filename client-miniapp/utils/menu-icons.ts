/**
 * 生成可直接放进 `background-image` 的 data URI（url-encoded SVG）。
 *
 * 用 encodeURIComponent 而非 base64：可读、体积小，且小程序 WXSS 对
 * `data:image/svg+xml,` 的 url-encoded 形式支持稳定（真机已验证同类写法）。
 */
export function menuIcon(name: string): string {
  const body = ICON_PATHS[name] ?? ICON_PATHS.sparkles;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="${STROKE}" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  // 必须用单引号包 data URI：WXML 的 style 属性是双引号，url("...") 的双引号会截断属性
  // 导致图标变空白。SVG 内部的双引号已被 encodeURIComponent 编码成 %22，不会冲突。
  return `url('data:image/svg+xml,${encodeURIComponent(svg)}')`;
}
